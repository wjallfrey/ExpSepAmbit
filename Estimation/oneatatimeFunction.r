gammahatsijTime<-function(i,j,Y,timelags){
  Nx<-dim(Y[[1]])[2]
  NumberofLags<-length(timelags)
  output<-matrix(0,NumberofLags,Nx)
  for(k in 1:NumberofLags){
    Tlag<-timelags[k]
    output[k,]<-normalisedgammaijTimeHAT(i,j,Tlag,Y)
  }
  return(output)
}
