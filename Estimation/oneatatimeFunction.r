  if(mean){
    return(mean(gam))
  }
  else{return(gam)}
}
Cijhat0<-function(i,j,Y){#i,j=1,2
  yi<-Y[[i]]
  yj<-Y[[j]]
  return(mean(yi*yj))
}
CijhatTime<-function(i,j,Tlag,Y){#i,j=1,2
  yi<-Y[[i]]
  yj<-Y[[j]]
  deltat<-Y[[6]]
  c<-Y[[5]]
  Nt<-dim(yi)[1]
  Nx<-dim(yi)[2]
  return(colMeans(yi[1:(Nt-Tlag/(2*deltat)),1:(Nx)]*yj[(Tlag/(2*deltat)+1):Nt,(1):Nx]))
}
CijhatSpace<-function(i,j,Llag,Y){#i,j=1,2
